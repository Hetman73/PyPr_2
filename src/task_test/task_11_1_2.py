def fibonacci():
    """генератор чисел Фибоначчи."""
    a, b = 0, 1
    while True:
        yield a  # Отдаем текущее число
        a, b = b, a + b  # Готовим следующие два числа


# Использование:
f = fibonacci()

print(next(f))  # 0
print(next(f))  # 1
print(next(f))  # 1
print(next(f))  # 2
print(next(f))  # 3

