from pathlib import Path

current_dir = Path(__file__).resolve().parent
file_path = current_dir.parent.parent / "doks" / "nums.txt"


def sum_filtered_digits():
    with open(file_path, "r") as f:
        # 1. Разбиваем по #, берем первую часть, убираем пробелы и \n
        # 2. Отбрасываем пустые строки
        rows = (row.split('#')[0].strip() for row in f)
        nums = (n for n in rows if n.isdigit())
        total = 0
        for n in nums:

                total += int(n)


        return f"the sum is {float(total)}"





if __name__ == "__main__":
    print(sum_filtered_digits())

